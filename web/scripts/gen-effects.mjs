// Generates the board effect modules from the approved prototypes, so the game uses exactly
// the animations that were approved there. Run: node scripts/gen-effects.mjs
// Sources: ../prototypes/capture-effect.html (captures) and ../prototypes/place-effect.html (placement).
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const proto = (name) => readFileSync(join(here, '..', '..', 'prototypes', name), 'utf8').split('\n');

// lines between the first line that starts with `from` (inclusive) and the first later line that starts with `to` (exclusive)
function slice(lines, from, to) {
  const a = lines.findIndex((l) => l.startsWith(from));
  if (a < 0) throw new Error('marker not found: ' + from);
  const b = lines.findIndex((l, i) => i > a && l.startsWith(to));
  if (b < 0) throw new Error('marker not found: ' + to);
  return lines.slice(a, b).join('\n');
}

const header = (src) => `// @ts-nocheck
// GENERATED by scripts/gen-effects.mjs from prototypes/${src}. Do not edit by hand:
// change the prototype, get it approved, then regenerate.
`;

// ---- captures ----
{
  const L = proto('capture-effect.html');
  const shaders = slice(L, '  const NOISE = `', '  let shard, part, fire, fog;');
  const setup = slice(L, '  const quadVao = gl.createVertexArray();', '  function rng(seed)');
  const stones = slice(L, '  function rng(seed)', '  // Big single stones');
  const draw = slice(L, '  const smooth = ', '  const playBtn');
  const out = `${header('capture-effect.html')}
export function createCapture(gl, atlas) {
  let W = 1, H = 1, dpr = 1;
  const DURATION = 1.4;
  const CAP_T = 0;
${shaders}
  const shard = program(shardVS, shardFS), part = program(partVS, partFS), fire = program(shardVS, fireFS), fog = program(shardVS, fogFS);
  let MAX_POINT = gl.getParameter(gl.ALIASED_POINT_SIZE_RANGE)[1];
${setup}
${stones}
${draw}
  return {
    makeStone, drawStone, windStartOf, windOf, DURATION, WIND_DUR, WIND_SWEEP, WIND_PAUSE,
    setSize(w, h, d) { W = w; H = h; dpr = d; MAX_POINT = gl.getParameter(gl.ALIASED_POINT_SIZE_RANGE)[1] / d; },
    bindTex() { gl.activeTexture(gl.TEXTURE0); gl.bindTexture(gl.TEXTURE_2D, tex); },
  };
}
`;
  writeFileSync(join(here, '..', 'src', 'board', 'gen', 'capture.js'), out);
}

// ---- placement ----
{
  const L = proto('place-effect.html');
  const shaders = slice(L, '  const NOISE = `', '  let stoneP, decalP, partP;');
  const setup = slice(L, '  const quadVao = gl.createVertexArray();', '  function rng(seed)');
  const rest = slice(L, '  function rng(seed)', '  const THAW_NAMES');
  const out = `${header('place-effect.html')}
export function createPlace(gl, atlas) {
  let W = 1, H = 1, dpr = 1;
${shaders}
  const stoneP = program(VS, STONE_FS), decalP = program(VS, DECAL_FS), partP = program(PART_VS, PART_FS);
${setup.replace('const MAX_POINT', 'let MAX_POINT')}
${rest}
  return {
    makeStone, drawPlacement, T,
    setSize(w, h, d) { W = w; H = h; dpr = d; MAX_POINT = gl.getParameter(gl.ALIASED_POINT_SIZE_RANGE)[1] / d; },
    bindTex() { gl.activeTexture(gl.TEXTURE0); gl.bindTexture(gl.TEXTURE_2D, tex); },
  };
}
`;
  writeFileSync(join(here, '..', 'src', 'board', 'gen', 'place.js'), out);
}
